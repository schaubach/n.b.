const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const root = path.resolve(__dirname, "..");
const pkg = require(path.join(root, "package.json"));

function run(command) {
  try {
    return execSync(command, { cwd: path.resolve(root, ".."), stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch (error) {
    return "";
  }
}

const gitSha = process.env.REACT_APP_GIT_SHA || run("git rev-parse --short=12 HEAD") || "unknown";
const builtAt = new Date().toISOString();
const version = {
  app: "n.b.",
  version: pkg.version || "0.0.0",
  gitSha,
  builtAt,
  buildId: `${pkg.version || "0.0.0"}-${gitSha}-${builtAt}`,
};

fs.writeFileSync(path.join(root, "public", "app-version.json"), JSON.stringify(version, null, 2) + "\n");
const generatedDir = path.join(root, "src", "generated");
fs.mkdirSync(generatedDir, { recursive: true });
fs.writeFileSync(
  path.join(generatedDir, "appVersion.js"),
  "// Generated by scripts/write-app-version.js. Do not edit.\n" +
    "export const APP_VERSION = " + JSON.stringify(version, null, 2) + ";\n"
);
const gradeScaleDir = path.join(root, "public", "notenskala");
fs.mkdirSync(gradeScaleDir, { recursive: true });
const gradeScaleFiles = fs.existsSync(gradeScaleDir)
  ? fs.readdirSync(gradeScaleDir)
    .filter((name) => name.toLowerCase().endsWith(".csv"))
    .sort((a, b) => a.localeCompare(b, "de", { sensitivity: "base" }))
  : [];
fs.writeFileSync(path.join(gradeScaleDir, "index.json"), JSON.stringify(gradeScaleFiles, null, 2) + "\n");
console.log(`Wrote app-version.json and appVersion.js (${version.buildId})`);
console.log(`Wrote notenskala/index.json (${gradeScaleFiles.length} CSV files)`);
